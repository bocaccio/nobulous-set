NAP_GAP = 8.75

-- The Assignment deck, top left, with the Time Slots running down
-- underneath it and four Assignment spaces beside each.
ASSIGN_X = -19.5

-- FOUR SPACES PER TIME SLOT, because rules/nap.html says never exceed 4
