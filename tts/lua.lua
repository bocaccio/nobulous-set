FACEUP = {0, 180, 0}
FACEDOWN = {0, 180, 180}
-- WHERE EVERYTHING GOES, in multiples of a card. CARD_SCALE, CARD_W and
-- CARD_L are generated by build_mod.py from the one constant there, so
-- changing how big a card is respaces the whole table instead of needing
-- thirty literals edited here.
-- The felt is about 56 by 37 - x +/-28, z -18 to +19 - measured off the
-- dice, whose world positions are known, in a screenshot of the table.
-- A card is 8.71 long now, so four rows is all that fits, and they only
-- fit because the mat and the bags moved up onto the back rail.
-- FOUR ROWS OF 8.71 IS 34.84 IN 37 OF FELT, so the pitch is 8.8 - one
-- card and a hair. There is no room for a fifth row and none for a
-- generous gap; what bought these four was moving the mat and the bags
-- up onto the back rail.
-- FOUR CARD ROWS AND THE DICE, in 37 units of felt. Four rows of 8.71
-- at a pitch of 8.8 left nothing underneath, so every row moved up as
-- far as the back rail allows - the top row reaches 18.86 and the felt
-- ends at 19 - and the dice took what was left. There is no slack
-- anywhere in this column of numbers.
ROW_CHAR = 14.8                    -- characters, nearest the back rail
                                   -- (every card on this row is
                                   -- landscape, so it reaches 17.92 and
                                   -- the mat overhangs the felt at 18)
ROW_MAIN = 5.7                     -- the decks you draw from
ROW_SIDE = -3.1                    -- mats, slots and the Research Pool
ROW_TIER = -11.9                   -- what a tier adds

-- A single card a tier deals sits out at the right, on the SIDE row
-- rather than the tier row: the tier row is the lowest cards on the
-- table, and keeping it clear at the right-hand end is what gives the
-- exhausted dice the whole bottom band.
TIER_X = 24.0

-- The NAP Time Slot column, down the left. It has to clear the dice at
-- -26.5 on one side and the Assignment deck, which reaches -14.07, on
-- the other; a landscape card is 8.71 across, so there is exactly one
-- place for it.
SLOT_X = -19.5

-- NAP's right-hand column: the Apprentices to choose from, then the FINF
-- card, then the Final Exams, top to bottom. 7.0 apart, which clears a
-- landscape card's 6.24 depth, and the last of them sits at -14.4 with
-- its bottom edge at -17.5 - the deepest anything goes on this felt.
NAP_X = 23.5
-- 8.75 is the FLOOR, not a preference: an Assignment turned on its side
-- is 8.71 deep, so anything tighter has a rotated card lapping into the
-- next row. 7.0 did not clear it at all, 9.0 cleared it with a third of
