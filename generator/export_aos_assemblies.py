"""Export the authoritative AoS Assembly data for the browser playtest.

The lab used to carry its own transcription of every AoS table. For the
Assemblies it reads this file instead, because an Assembly holds two things
that must not drift apart and one that must not be stored twice:

  * the Build recipe, which decides what the lab will let you install;
  * the back's (colour, Target) elements, which the lab must conceal until
    the stage is revealed;
  * the Advanced colors line, which is DERIVED from the back by
    aos.advanced_colors and is exported alongside it only so the lab does
    not have to re-derive it. Four of the nine Assemblies print a recipe in
    colours their own back never asks for, so a lab that guessed one from
    the other would show the player the wrong promise.

check_app_sync.py holds the exported file against generator/aos.py.
"""

import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / "generator"))

from aos import ALL_ASSEMBLIES, ASSEMBLY_FLAVOR, COVERT, advanced_colors

LONG = {"P": "purple", "B": "blue", "G": "green", "Y": "yellow"}

cards = []
for name, recipe, back_name, elements in ALL_ASSEMBLIES:
    cards.append(dict(
        name=name,
        tier3=(name == COVERT[0]),
        build=[LONG[c] for c in recipe],
        advancedColors=[LONG[c] for c in advanced_colors(elements)],
        backName=back_name,
        # One entry per element of the finale stage, in printed order.
        backColors=[LONG[c] for c in (c for c, _ in elements)],
        backTargets=[t for _, t in elements],
        flavorFront=ASSEMBLY_FLAVOR[name][0],
        flavorBack=ASSEMBLY_FLAVOR[name][1],
    ))

if len(cards) != 9:
    raise ValueError("Expected 9 Assemblies (8 base + Covert), found %d" % len(cards))
if sum(1 for c in cards if c["tier3"]) != 1:
    raise ValueError("Exactly one Assembly should be Tier III only")
for c in cards:
    if len(set(c["backColors"])) != 2:
        raise ValueError("%s: a back must use exactly two distinct colours" % c["name"])
    if c["advancedColors"] != sorted(set(c["backColors"]), key=c["backColors"].index):
        raise ValueError("%s: Advanced colors does not match its own back" % c["name"])

out = root / "playtest" / "dist" / "aos_assemblies.js"
out.write_text(
    "// GENERATED by generator/export_aos_assemblies.py - do not edit.\n"
    "window.AOS_ASSEMBLIES = "
    + json.dumps(cards, ensure_ascii=False, indent=2) + ";\n",
    encoding="utf-8")
print(out)
